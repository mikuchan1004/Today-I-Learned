package game_04;

/**
 * [LOL_Exam 실행 클래스 - 상속, 다형성(Polymorphism), 다운캐스팅 종합 실습]
 * 
 * 💡 핵심 흐름 요약:
 * 1. 자식 객체 직접 생성 및 사용 (VI, Jax)
 * 2. 다형성(Polymorphism)의 구현:
 *    - 부모 타입 그릇(Champ)에 자식 객체(바이, 잭스)를 담기 (업캐스팅: 자동 변환)
 *    - 겉보기에는 똑같은 Champ 타입이지만, .move()를 실행하면 각자의 오버라이딩된 개성 있는 메서드가 동작함!
 * 3. 매크로(Auto) 객체 활용:
 *    - Auto.run(Champ) 하나로 바이와 잭스를 모두 넘겨서 자동 실행
 * 4. 강제 형변환(다운캐스팅):
 *    - 부모 타입으로 감싸져 있던 바이 객체를 다시 원래 VI 타입으로 되돌려 고유 기능 실행
 */
public class LOL_Exam {

	public static void main(String[] args) {
		
		// ==========================================
		// 1. 자식 객체 직접 생성 (바이, 잭스)
		// ==========================================
		VI 바이 = new VI();
		바이.move();        // 바이가 오버라이딩한 이동: "앗흥 이동합니다. 앗흥"
		바이.skill("R");    // 부모 Champ로부터 물려받은 궁극기 사용
		
		Jax jax = new Jax();
		jax.move();         // 잭스가 오버라이딩한 이동: "잭스 온더 비치! 외치면서 바다로 이동"
		
		// ==========================================
		// 2. 다형성(Polymorphism) 테스트 - 부모 그릇에 자식 담기 (업캐스팅)
		// ==========================================
		// 자식(VI, Jax)은 부모(Champ)의 일종이므로, 부모 타입 변수에 자연스럽게 담을 수 있습니다.
		Champ champ1 = 바이; // 바이를 Champ 타입으로 참조
		Champ champ2 = jax;  // 잭스를 Champ 타입으로 참조
		
		// 💡 [동적 바인딩 확인]
		// champ1, champ2 둘 다 'Champ' 타입이지만,
		// 실제로 실행되는 move()는 각 객체의 진짜 클래스(VI, Jax)에 정의된 메서드가 찾아가서 실행됩니다!
		champ1.move(); // 출력: "앗흥 이동합니다. 앗흥"
		champ2.move(); // 출력: "잭스 온더 비치! 외치면서 바다로 이동"
		
		// ==========================================
		// 3. 매개변수 다형성을 활용한 Auto 매크로 실행
		// ==========================================
		Auto auto = new Auto();
		
		// Auto의 run() 메서드는 매개변수가 (Champ champ) 하나뿐이지만,
		// 다형성 덕분에 바이와 잭스 모두 전달할 수 있습니다.
		auto.run(바이); // 바이의 공격/이동/스킬/귀환 + (instanceof 통과) "징크스야~ 놀~~~~자" 실행
		auto.run(jax);  // 잭스의 공격/이동/스킬/귀환 실행 (바이 고유 기능은 통과하지 않고 안전하게 건너뜀)
		
		// ==========================================
		// 4. 다운캐스팅 (Downcasting) 예시
		// ==========================================
		// champ1은 현재 부모인 Champ 타입이므로 'champ1.징크스랑놀기()'를 바로 호출할 수 없습니다.
		// 아래처럼 (VI)로 강제 형변환(다운캐스팅)을 해주면 바이만의 고유 기능을 다시 호출할 수 있게 됩니다.
//		VI vi2 = (VI)champ1;
//		vi2.징크스랑놀기();

	}

}
