package game_04;

/**
 * [VI 클래스 - 챔피언 '바이' (Champ를 상속받은 자식 클래스)]
 * 
 * 💡 핵심 개념:
 * 1. extends Champ:
 *    - Champ의 기본 공격, 스킬, 귀환 기능을 그대로 물려받습니다.
 * 2. 메서드 오버라이딩 (@Override):
 *    - 부모의 move() 메서드를 바이의 고유한 이동 대사로 재정의했습니다.
 * 3. 자식 클래스만의 고유 메서드 (징크스랑놀기):
 *    - 부모(Champ)에게는 없고 오직 바이(VI)에게만 있는 특별한 기능입니다.
 *    - 💡 중요: 만약 'Champ champ = new VI();' 처럼 부모 타입으로 바이 객체를 참조하면,
 *      부모 규격에 '징크스랑놀기'가 정의되어 있지 않아 바로 호출할 수 없습니다.
 *      이때 원래 바이 타입으로 되돌리는 '다운캐스팅((VI)champ)'이 필요합니다!
 */
public class VI extends Champ {
	
	/**
	 * [오버라이딩] 바이만의 이동 동작
	 * 부모의 기본 이동 메서드를 덮어써서 실행됩니다.
	 */
	@Override
	void move() {
		System.out.println("앗흥 이동합니다. 앗흥");
	}
	
	/**
	 * 바이만의 고유 메서드 (부모 Champ에는 없는 특별한 기능)
	 */
	void 징크스랑놀기() {
		System.out.println("징크스야~ 놀~~~~자");
	}
}
