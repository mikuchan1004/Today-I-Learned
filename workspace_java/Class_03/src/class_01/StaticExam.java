package class_01;

/**
 * ============================================================================
 * [StaticExam.java - static 멤버 접근 방법 및 Math 클래스 활용]
 * ============================================================================
 * 
 * 1. static 멤버를 다룰 때의 핵심 포인트
 *    - static 멤버(필드, 메서드)는 객체(인스턴스)의 소유가 아닌 '클래스'의 소유입니다.
 *    - 따라서 '참조변수.멤버'로 접근하지 않고, '클래스명.멤버'로 직접 접근하는 것이 자바의 표준 권장 문법입니다.
 */
public class StaticExam {
	
	public static void main(String[] args) {
		// -------------------------------------------------------------
		// 1. 객체를 통한 static 멤버 접근 (비권장 방식)
		// -------------------------------------------------------------
		// static 변수는 메모리에 딱 1개만 존재하여 모든 인스턴스가 공유합니다.
		// 아래처럼 s1으로 접근해서 PI를 3.1로 바꾸어버리면,
		// s1뿐만 아니라 아무런 짓도 안 한 s2의 getPI() 값마저 똑같이 3.1로 바뀌어버립니다!
		// 또한 "The static field Static_03.PI should be accessed in a static way"라는 경고가 뜹니다.
//		Static_03 s1 = new Static_03();
//		Static_03 s2 = new Static_03();
//		
//		s1.PI = 3.1;
//		System.out.println(s1.getPI());
//		System.out.println(s2.getPI());
//		
		
		// -------------------------------------------------------------
		// 2. 클래스 이름을 통한 static 멤버 접근 (표준 정석 방식)
		// -------------------------------------------------------------
		// new로 객체를 만들 필요 없이, '클래스이름.변수명' 또는 '클래스이름.메서드명()'으로 바로 호출합니다.
		System.out.println(Static_03.PI);    // static 변수 직접 조회 (3.14)
		System.out.println(Static_03.getPI()); // static 메서드 직접 호출 (3.14)
		
		// -------------------------------------------------------------
		// 3. 자바 표준 라이브러리(JDK) 속 static의 대표 예시: Math 클래스
		// -------------------------------------------------------------
		// 우리가 수학 계산을 할 때 Math 객체를 new Math()로 만들지 않습니다.
		// Math 안의 모든 기능(원주율, 절대값, 제곱근, 난수 등)은 이미 static으로 만들어져 있어서
		// 바로 'Math.기능명'으로 가져다 쓸 수 있도록 설계되어 있습니다.
		System.out.println(Math.PI);     // Math 클래스의 static 상수 PI (3.141592653589793)
		System.out.println(Math.random()); // Math 클래스의 static 메서드 (0.0 이상 ~ 1.0 미만의 무작위 난수 반환)
		
		// -------------------------------------------------------------
		// 4. 같은 클래스 내의 static 메서드 호출
		// -------------------------------------------------------------
		// main 메서드도 'public static void main'으로 static 메서드입니다.
		// static 블록 안에서 같은 클래스에 있는 다른 static 메서드(test)를 호출할 때는,
		// 객체를 생성(new StaticExam())할 필요 없이 메서드 이름(test())만으로 바로 호출할 수 있습니다!
//		StaticExam se = new StaticExam();
//		se.test();
		test(); // 바로 호출 가능
	}
	
	// static 메서드 정의
	static void test() {
		System.out.println("테스트");
	}
}
