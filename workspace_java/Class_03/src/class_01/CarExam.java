package class_01;

/**
 * ============================================================================
 * [CarExam.java - 객체(인스턴스) 생성 및 Car_02 클래스 실습]
 * ============================================================================
 * 
 * 1. 실행 클래스(main 메서드)란?
 *    - 자바 프로그램이 실행될 때 가장 먼저 시작되는 진입점(Entry Point)입니다.
 *    - Car_02 설계도를 바탕으로 실제 자동차 객체(c1, c2)를 메모리에 만들고 동작시킵니다.
 */
public class CarExam {

	public static void main(String[] args) {
		// -------------------------------------------------------------
		// 1. 기본 자료형(Primitive Type) 변수
		// -------------------------------------------------------------
		// 변수 a라는 공간에 직접 숫자 10이라는 실제 값이 저장됩니다.
		int a;
		a = 10;
		System.out.println(a);
		
		// -------------------------------------------------------------
		// 2. 참조 자료형(Reference Type) 변수 및 객체 생성
		// -------------------------------------------------------------
		// new Car_02():
		//   - 힙(Heap) 메모리 영역에 Car_02 객체(자동차 1대)를 실제로 생성합니다.
		//   - 이때 Car_02() 기본 생성자가 호출되어 "생성자 실행"이 출력됩니다.
		// c1, c2 (참조 변수):
		//   - 객체 자체가 저장되는 것이 아니라, 힙 메모리에 생성된 자동차 객체의 '주소값(리모컨)'을 가집니다.
		//   - c1과 c2는 서로 완전히 다른 독립된 자동차 객체입니다!
		Car_02 c1 = new Car_02();
		Car_02 c2 = new Car_02();
		
		// -------------------------------------------------------------
		// 3. 필드(멤버 변수) 접근 및 조회
		// -------------------------------------------------------------
		// 객체명.필드명 형태로 접근합니다.
		int ms = c1.maxSpeed; // Car_02에 정의된 기본값 240이 대입됨
		int s = c1.speed;     // 명시적으로 초기화하지 않았으므로 int 기본값 0이 나옴
		System.out.println("c1.speed:" + s); // "c1.speed:0" 출력
		
		// -------------------------------------------------------------
		// 4. 각 객체의 독립성 확인
		// -------------------------------------------------------------
		// c1의 speed를 400으로 변경해도, c2의 speed에는 전혀 영향을 미치지 않습니다.
		c1.speed = 400;
		c2.speed = 399;
		
		System.out.println(c1.speed); // 400 출력
		System.out.println(c2.speed); // 399 출력
		
		// -------------------------------------------------------------
		// 5. 메서드 호출을 통한 상태 변경
		// -------------------------------------------------------------
		System.out.println(c1.power); // 초기 상태: false (시동 꺼짐)
		
		// powerOn() 메서드를 호출하여 내부 필드 power를 true로 변경
		c1.powerOn();
		System.out.println(c1.power); // 변경 후 상태: true (시동 켜짐)
		
		// -------------------------------------------------------------
		// 6. 세터(Setter) 메서드 호출과 유효성 검사
		// -------------------------------------------------------------
		// setSpeed(400)을 호출하면:
		// 내부에서 maxSpeed(240)와 비교하여 400이 더 크므로 
		// "그만 올려!!"를 출력하고 speed를 최고 속도인 240으로 보정하여 저장합니다.
		c1.setSpeed(400);
		System.out.println(c1.speed); // 240 출력
		
		// -------------------------------------------------------------
		// 7. 게터(Getter) 메서드 호출
		// -------------------------------------------------------------
		// 현재 자동차의 속도(240)를 반환받아 변수 s1에 저장
		int s1 = c1.getSpeed();
		
		// -------------------------------------------------------------
		// 8. 오버로딩된 메서드 호출
		// -------------------------------------------------------------
		// 전달인자가 정수 2개(1, 2)이므로 
		// Car_02 클래스에서 int plus(int x, int y) 메서드가 정확히 매칭되어 호출됩니다.
		c1.plus(1, 2);

	}

}
