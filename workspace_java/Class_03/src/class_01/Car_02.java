package class_01;

/**
 * ============================================================================
 * [Car_02.java - 객체지향 프로그래밍: 클래스 설계, 필드, 메서드, 오버로딩, 생성자]
 * ============================================================================
 * 
 * 1. 클래스(Class)란?
 *    - 객체(인스턴스)를 만들기 위한 '설계도' 또는 '틀'입니다.
 *    - 클래스는 속성(상태)을 나타내는 '필드(Field)'와 동작(기능)을 나타내는 '메서드(Method)'로 구성됩니다.
 */
public class Car_02 {
	
	// ========================================================================
	// [1] 필드 (Field / 멤버 변수 / 전역 변수)
	// ========================================================================
	// - 객체가 가지는 고유한 속성(데이터)을 저장하는 변수입니다.
	// - 필드는 선언만 하거나, 선언과 동시에 초기값을 대입할 수 있습니다.
	
	String Company = "쉐보레"; // 선언과 동시에 명시적 초기화
//	String model = "임팔라";
	String model;              // 선언만 한 상태 (참조 타입이므로 기본값 null로 자동 초기화)
	int maxSpeed = 240;        // 최고 속도 240으로 초기화
	int year;                  // 기본값 0으로 자동 초기화
	
	// [필드의 기본 초기값 규칙]
	// 로컬 변수(메서드 안의 변수)는 초기화하지 않으면 사용할 수 없지만,
	// 클래스의 '필드'는 초기화하지 않아도 객체 생성(new) 시 자바가 기본값으로 자동 초기화해 줍니다.
	// - 정수형(byte, short, int, long) : 0
	// - 실수형(float, double) : 0.0
	// - 논리형(boolean) : false
	// - 참조형(String, 배열, 객체 등) : null
	int speed; // 초기화하지 않았으므로 0으로 자동 초기화됨
	
	// [주의: 필드 영역의 문법 규칙]
	// 클래스 블록 바로 아래(필드 영역)에서는 오직 '선언'과 '초기화 대입'만 가능합니다.
	// 연산, 메서드 호출, 조건문, 단순 대입문 같은 '실행(동작) 코드'는 반드시 메서드나 생성자 블록 내부에서만 작성해야 합니다.
//	speed = 10; // 컴파일 에러: 필드 영역에서는 단독 실행문 작성 불가!
	
	boolean power; // 기본값 false로 자동 초기화됨 (시동 꺼짐 상태)
	
	// ========================================================================
	// [2] 메서드 (Method / 기능)
	// ========================================================================
	// - 객체가 수행할 동작이나 행위를 정의하는 블록입니다.
	// - 문법: [리턴타입] [메서드명](<[전달인자/매개변수 목록]>) { 실행할 코드 }
	
	// [시동 켜기 메서드]
	// void: 실행 후 호출한 곳으로 돌려줄 값(반환값)이 없음을 의미합니다.
	void powerOn() {
		power = true; // 시동 상태를 true(켜짐)로 변경
	}
	
	// [시동 끄기 메서드]
	void powerOff() {
		power = false; // 시동 상태를 false(꺼짐)로 변경
	}
	
	// [속도 설정 세터(Setter) 메서드]
	// 전달받은 매개변수 s 값을 speed 필드에 반영합니다.
	// 단, 안전을 위해 최고 속도(maxSpeed)를 넘어서면 최고 속도로 제한합니다.
	void setSpeed(int s) {
		System.out.println("s:" + s);
		
		if (s >= maxSpeed) {
			s = maxSpeed; // 최고 속도로 고정
			System.out.println("그만 올려!!");
		}
		speed = s;
		return; // void 메서드에서 return;은 메서드를 즉시 종료하고 빠져나간다는 의미 (생략 가능)
	}
	
	/*
	 * [속도 조회 게터(Getter) 메서드]
	 * 현재 필드의 speed 값을 돌려줍니다.
	 * @param 없음 
	 * @return int (현재 속도 값)
	 */
	int getSpeed() {
		return speed; // int 타입의 speed 값을 호출한 곳으로 반환
	}
	
	// [매개변수를 받는 getSpeed 오버로딩]
	int getSpeed(int s) {
		System.out.println();
		System.out.println(s);
		return speed;
	}
	
	// ========================================================================
	// [3] 메서드 오버로딩 (Method Overloading)
	// ========================================================================
	// - '하나의 클래스 안에 이름이 같은 메서드를 여러 개 정의하는 것'입니다.
	// - 조건: 매개변수의 개수, 타입(자료형), 또는 순서가 서로 달라야 합니다. (리턴 타입만 다른 것은 인정되지 않음)
	// - 호출 우선순위:
	//   1. 전달인자의 자료형과 정확히 일치하는 메서드가 최우선 실행
	//   2. 정확히 일치하는 것이 없다면, 더 큰 범위의 자료형으로 자동 형변환(Widening)되어 들어갈 수 있는 메서드 실행
	
	int plus (int x, int y) {
		System.out.println("int plus(int x, int y)");
		return x + y;
	}
	
	// 매개변수가 1개인 plus 메서드
	// 전달받은 값 x를 두 번 더하기 위해, 위에서 정의한 plus(int, int) 메서드를 재호출(재사용)하고 있습니다.
	int plus (int x) {
		return plus(x, x);
//		return x + x;
	}
	
	int minus (int x, int y) {
		return x - y;
	}
	
	// 매개변수 타입이 double인 plus 메서드
	double plus (double x, double y) {
		System.out.println("int plus(double x, double y)");
		return x + y;
	}
	
	// ========================================================================
	// [4] 생성자 (Constructor)
	// ========================================================================
	// - 객체가 new 키워드로 생성될 때 단 한 번 호출되어 필드 초기화를 담당하는 특수한 블록입니다.
	// - 특징: 
	//   1. 이름이 클래스명(Car_02)과 완전히 동일해야 합니다.
	//   2. 리턴 타입(void 포함)을 절대 적지 않습니다.
	// - 기본 생성자(Default Constructor):
	//   클래스 안에 생성자를 하나도 정의하지 않으면, 컴파일러가 매개변수 없는 빈 기본 생성자를 자동으로 만들어 줍니다.
	//   하지만 매개변수가 있는 생성자를 하나라도 직접 정의하면, 기본 생성자는 자동으로 생성되지 않으므로 필요 시 직접 작성해야 합니다.
	
	// [기본 생성자]
	Car_02() {
		System.out.println("생성자 실행");
	}
		
	// [매개변수가 있는 생성자 (모델명, 연식, 시동여부를 한 번에 초기화)]
	Car_02(String m, int y, boolean p) {
		model = m;
		year = y;
		power = p;
	}
	
	// [생성자 오버로딩 및 this() 호출]
	Car_02(String m) {	
		// this(...) : 자신의 클래스 안에 있는 다른 생성자를 호출하는 특별한 키워드입니다.
		// 코드의 중복을 줄이기 위해, 위에서 작성한 Car_02(String m, int y, boolean p) 생성자를 호출하여 초기화 작업을 위임합니다.
		// ※ 주의: this(...) 생성자 호출문은 반드시 생성자의 '첫 번째 줄'에만 위치해야 합니다!
		this (m, 2026,false);
//		model = m;
//		year = 2026;
//		power = false;
		
		System.out.println();
	}
	
	// [this 키워드를 사용한 세터 메서드]
	// 매개변수 이름(year)과 필드 이름(year)이 같을 때,
	// 'this.year'는 이 객체의 필드(멤버 변수)를 가리키고, 우변의 'year'는 매개변수를 가리킵니다.
	void setYear(int year) {
		this.year = year;
	}
}
