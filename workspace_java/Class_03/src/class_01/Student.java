package class_01;

/**
 * ============================================================================
 * [Student.java - 자바 소스 파일 구조와 다중 클래스 선언 규칙]
 * ============================================================================
 * 
 * 1. 하나의 소스 파일(.java)에 여러 클래스를 작성할 때의 중요한 문법 규칙
 * 
 *    (1) 'public' 클래스는 파일당 단 1개만 존재할 수 있습니다.
 *        - 여러 클래스에 public을 붙이면 컴파일 에러가 발생합니다.
 * 
 *    (2) 'public'이 붙은 클래스의 이름은 반드시 소스 파일명과 대소문자까지 완전히 일치해야 합니다.
 *        - 파일명이 'Student.java'이므로, 'public class Student'만 가능합니다.
 * 
 *    (3) public이 붙지 않은 다른 클래스(class Teacher)는 여러 개 선언할 수 있습니다.
 *        - 이때 접근 제어자는 자동으로 'default(package-private)'가 됩니다.
 *        - 'default' 클래스는 같은 패키지(package class_01;) 안에서만 접근하여 사용할 수 있습니다.
 */

// 파일명과 동일한 public 클래스
