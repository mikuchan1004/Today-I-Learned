package class_01;

/**
 * ============================================================================
 * [Static_03.java - static 키워드: 정적 필드, 정적 메서드, 상수(static final)]
 * ============================================================================
 * 
 * 1. static(정적)이란?
 *    - '고정된'이라는 의미로, 객체(인스턴스)를 new 하지 않고도 프로그램 실행 시 메모리(메서드 영역)에 딱 1개만 로딩됩니다.
 *    - 특정 객체에 소속되는 것이 아니라 '클래스 자체'에 소속되므로, 
 *      모든 객체들이 하나의 값을 '공동으로 공유'할 때 사용합니다.
 *    - 호출 방법: 클래스명.정적멤버명 (예: Static_03.PI)
 */
public class Static_03 {
	// ========================================================================
	// [1] static 변수 (정적 변수 / 클래스 변수)
	// ========================================================================
	// new로 객체를 생성하지 않고도 클래스 이름(Static_03.PI)으로 바로 접근할 수 있습니다.
	// 이 클래스로부터 만들어지는 모든 객체가 같은 PI 값을 함께 공유합니다.
	static double PI = 3.14;
	
	// [인스턴스 변수 (일반 필드)]
	// static이 붙지 않은 변수는 반드시 new 연산자로 객체를 생성해야만 힙 메모리에 생깁니다.
	// 객체마다 독립된 name 공간을 갖습니다.
	String name;
	
	// ========================================================================
	// [2] 상수 선언 : static final
	// ========================================================================
	// - static : 객체마다 따로 만들 필요 없이 클래스 차원에서 단 하나만 존재 (메모리 절약)
	// - final  : 한 번 정해진 값을 절대로 변경할 수 없음 (불변성 보장)
	// -> 즉, 프로그램 전체에서 공유하며 절대 바뀌면 안 되는 '공용 고정값'을 만들 때 사용합니다.
	// ※ 명명 규칙: 상수는 보통 모두 대문자로 작성하며, 단어 사이는 언더바(_)로 연결합니다.
	
	static final String 주민번호 = "123456-1";
	
	// 실무에서 상태 코드나 에러 코드를 상수로 정의해두면 오타를 방지하고 가독성을 높일 수 있습니다.
	static final String OK = "E00";
	static final String FILTER_ERROR = "E01";
	static final String COOLER_ERROR = "E02";
	
	// ========================================================================
	// [3] static 메서드 (정적 메서드)
	// ========================================================================
	// 객체 생성 없이 'Static_03.getPI()' 형태로 바로 호출할 수 있는 메서드입니다.
	static double getPI()
	{
		// [매우 중요한 개념: static 메서드 안에서는 인스턴스 변수 사용 불가!]
		// name은 객체가 new 되어야만 메모리에 존재하는 '인스턴스 변수'입니다.
		// 하지만 static 메서드(getPI)는 객체가 아예 생성되지 않은 상태에서도 언제든 실행될 수 있습니다.
		// 객체가 아직 태어나지도 않았는데 그 객체의 name을 쓰라고 하면 자바는 어떤 객체의 name인지 알 수 없으므로
		// 컴파일 에러("non-static variable name cannot be referenced from a static context")가 발생합니다!
//		name = "abc";
		
		// 반면 PI는 같은 static 멤버이므로 객체 없이도 언제나 존재하므로 안전하게 접근 가능합니다.
		return PI;
		
	}
	
	// ========================================================================
	// [4] 인스턴스 메서드
	// ========================================================================
	// static이 붙지 않았으므로 반드시 객체를 생성한 후 호출해야 합니다.
	// 인스턴스 메서드 내부에서는 static 변수(PI)와 인스턴스 변수(name) 모두 자유롭게 접근할 수 있습니다.
	void setPI(double p) {
		PI = p;
	}
	
	// ========================================================================
	// [5] 생성자
	// ========================================================================
	// new Static_03() 할 때 실행됩니다.
	// static 변수인 PI를 생성자에서 재설정하고 있습니다.
	Static_03() {
		PI = 3.14;
	}
}
