package string_09;

/**
 * [문자열(String) 다루기 실습]
 * - 자바에서 문자열을 검색하고, 자르고, 바꾸고, 검사하는 가장 핵심적인 기능 모음
 */
public class StringExam {

	public static void main(String[] args) {
		String s = "영일이삼사오육칠팔구삼사";
		
		// [1] 특정 위치(인덱스)의 글자 하나 가져오기 (0부터 시작: 0=영, 1=일, 2=이, 3=삼)
		char c = s.charAt(3);
		System.out.println(c); // 출력: 삼
		
		// [2] 문자열의 전체 글자 수(길이) 구하기
		System.out.println(s.length()); // 출력: 12
		
		// [3] 앞에서부터 특정 글자가 처음 등장하는 위치(인덱스) 찾기
		int i = s.indexOf("삼사");
		System.out.println(i); // 출력: 3 (3번째 위치에서 "삼사" 시작)
		
		// [4] 뒤에서부터 거꾸로 검색하여 마지막으로 등장하는 위치(인덱스) 찾기
		int i2 = s.lastIndexOf("삼사");
		System.out.println(i2); // 출력: 10 (10번째 위치의 "삼사")
		
		// -------------------------------------------------------------
		// [실습] 이메일 유효성 검사 2가지 방식
		// -------------------------------------------------------------
		String email = "tsunderechan@naver.com";
		
		// 방법 A: indexOf() 내장 메서드 사용
		// indexOf는 찾는 글자가 없으면 -1을 반환합니다.
		// 즉, @와 .의 위치가 모두 -1이 아니면 둘 다 존재한다는 뜻!
		if(email.indexOf("@") != -1 && email.indexOf(".") != -1 ) {
			System.out.println("이메일 맞음");
		} else {
			System.out.println("이메일 아님");
		}
		
		// 방법 B: indexOf를 쓰지 않고 for 반복문과 charAt()으로 직접 구현하기
		int cnt_골벵이 = -1; // @가 발견된 위치 저장 (발견 못 하면 -1 유지)
		int cnt_쩜 = -1;     // .이 발견된 위치 저장 (발견 못 하면 -1 유지)
		
		for(int j = 0; j < email.length(); j++) {
			if(email.charAt(j) == '@') {
				cnt_골벵이 = j; // @를 찾으면 해당 위치(인덱스) 기록
			} else if (email.charAt(j) == '.') {
				cnt_쩜 = j;    // .을 찾으면 해당 위치(인덱스) 기록
			}
		}
		
		// 둘 다 발견되었는지(-1이 아닌지) 확인
		if (cnt_골벵이 != -1 && cnt_쩜 != -1) {
			System.out.println("이메일 맞음 :" + cnt_골벵이 + "," + cnt_쩜);
	 	} else {
	 		System.out.println("이메일 아님");
	 	}
		
		// -------------------------------------------------------------
		// [5] 문자열 내용 바꾸기 (replace)
		// -------------------------------------------------------------
		// 주의: 원본 s는 바뀌지 않고, 변환된 새로운 문자열이 s2에 대입됩니다. (String의 불변성)
		String s2 = s.replace("삼사" , "34");
		System.out.println(s);  // 원본: 영일이삼사오육칠팔구삼사
		System.out.println(s2); // 변환본: 영일이34오육칠팔구34
		
		// -------------------------------------------------------------
		// [6] 문자열 일부분 잘라내기 (substring)
		// -------------------------------------------------------------
		// s.substring(시작, 끝): 시작 인덱스부터 '끝 인덱스 직전'까지 추출
		s2 = s.substring(5, 8); // 5번부터 7번까지 -> "오육칠"
		System.out.println(s2);
		
		// 시작 위치만 주면 끝까지 잘라냄
		s2 = s.substring(5);    // 5번부터 끝까지 -> "오육칠팔구삼사"
		System.out.println(s2);
		
		// -------------------------------------------------------------
		// [7] 특정 구분자를 기준으로 문자열 쪼개기 (split)
		// -------------------------------------------------------------
		// "삼" 글자를 기준으로 앞뒤로 쪼개어 배열(String[])에 담아줍니다.
		String[] s3 = s.split("삼");
		for (String a : s3) {
			System.out.println(a);
		}
		
		// -------------------------------------------------------------
		// [8] 0.0 이상 1.0 미만의 무작위 난수(실수) 생성 (Math.random)
		// -------------------------------------------------------------
		double r = Math.random();
		System.out.println(r);
	}

}
