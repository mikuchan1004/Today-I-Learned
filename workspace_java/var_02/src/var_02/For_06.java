package var_02;

public class For_06 {

	public static void main(String[] args) {
		
		/* ====================================================================
		 * 1. for 반복문의 기본 구조와 실행 순서
		 * ====================================================================
		 * for (초기식; 조건식; 증감식) { 실행문; }
		 * 
		 * [실행 순서]
		 * 1) 초기식 실행 (int i = 0) -> 딱 1번만 실행
		 * 2) 조건식 검사 (i < 10)    -> 참이면 본문 실행, 거짓이면 반복문 종료
		 * 3) 본문 실행 (System.out.println(i))
		 * 4) 증감식 실행 (i++)        -> i가 1 증가한 뒤 다시 2번 조건식으로 이동
		 */
		// 무한 루프의 형태 (조건식을 비워두면 항상 참으로 간주됨)
//		for (; ;) {
//			
//		}
		
		// 0부터 9까지 10회 반복 출력
		for (int i=0; i<10; i++) {
			System.out.println(i);
		}
		
		
		/* ====================================================================
		 * 2. 0부터 10까지 모두 더하기 (누적 합산 알고리즘)
		 * ====================================================================
		 * - 합계를 담을 변수(result)를 반복문 '바깥'에서 0으로 초기화해 두는 것이 핵심!
		 * - result += i  ==>  result = result + i 와 동일한 의미
		 */
		// 0부터 10까지 모두 더하시오
		int result = 0;
		for (int i=0; i<11; i++) { // i가 0부터 10까지 총 11회 회전
			result += i;		
		}
		System.out.println(result); // 0 + 1 + 2 + ... + 10 = 55
		
		
		/* ====================================================================
		 * 3. 문제 1 : 주사위 2개를 굴려서 나올 수 있는 모든 조합 출력 (이중 for문)
		 * ====================================================================
		 * - 바깥쪽 for문(i)이 1번 돌 때, 안쪽 for문(j)은 전체를 다 돎!
		 * - [참고 주의사항]
		 *   원래 주사위 눈은 1~6이므로 조건식이 i<=6, j<=6 이어야 해.
		 *   (아래 코드는 i<6, j<6 이라서 1~5까지만 출력됨에 유의할 것!)
		 */
		// 문제1 
		// 주사위 2개를 굴려서 
		// 나올 수 있는 모든 조합 출력
		for (int i=1; i<6; i++) {
			for (int j=1; j<6; j++) {
				System.out.println("나올 수 있는 모든 출력 :" + i + " " + j);
			}
		}
		
		
		/* ====================================================================
		 * 4. 문제 2 : 주사위 2개를 굴려 합계(k) 별로 조합 출력
		 * ====================================================================
		 * - 두 주사위 합의 최솟값은 1+1=2, 최댓값은 6+6=12.
		 * - 가장 바깥 for문(k)으로 합계 2부터 12까지 기준을 잡고,
		 *   안쪽의 주사위 조합(i, j) 중 합이 k와 같은 것만 골라 출력함.
		 * - printf("[%d, %d]", i, j) : 서식에 맞춰 깔끔하게 가로로 출력 (%d는 정수)
		 */
		// 문제2
		// 주사위 2개를 굴려서
		// 나올 수 있는 모든 조합을 
		// 합 별로 출력
		for (int k=2; k<=12; k++) {
			System.out.print(k + ":");
			for(int i=1; i<=6; i++) {
				for (int j=1; j<=6; j++) {
					if (i+j == k) {
						System.out.printf("[%d, %d]" , i, j);
					}
				}
			}
			System.out.println(); // 줄바꿈
		}
		
		
		/* ====================================================================
		 * 5. 문제 3 : 합계별 주사위 조합 출력 (단, 중복 제거)
		 * ====================================================================
		 * - 주사위 눈 [1, 2]와 [2, 1]은 순서만 다르고 구성 숫자가 같으므로 중복이야.
		 * - 중복 제거 핵심 조건: `i <= j`
		 *   첫 번째 주사위(i)가 두 번째 주사위(j)보다 작거나 같을 때만 허용하면,
		 *   [1, 2]는 통과하고 [2, 1]은 걸러져서 깔끔하게 중복이 사라져!
		 */
		// 문제3
		// 주사위 2개를 굴려서
		// 나올 수 있는 모든 조합을 
		// 합 별로 출력
		// 단, 중복 없이
		for (int k=2; k<=12; k++) {
			System.out.print(k + ":");
			for(int i=1; i<=6; i++) {
				for (int j=1; j<=6; j++) {
					if (i+j == k && i <= j ) { // i <= j 조건으로 뒤집힌 중복 제거
						System.out.printf("[%d, %d]" , i, j);
					}
				}
			}
			System.out.println(); // 줄바꿈
		}
	}

}
