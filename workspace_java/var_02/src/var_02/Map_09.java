package var_02;

import java.util.ArrayList;
import java.util.HashMap;
import java.util.List;
import java.util.Map;

/**
 * ============================================================================
 * [Map_09.java - 컬렉션 프레임워크: Map(HashMap) & 실무 데이터 구조화]
 * ============================================================================
 * 
 * 1. Map 컬렉션이란?
 *    - 키(Key)와 값(Value)의 쌍(Pair, 엔트리)으로 데이터를 저장하는 자료구조입니다.
 *    - 사물함 열쇠(Key)로 사물함 안의 물건(Value)을 찾는 것과 같습니다.
 * 
 * 2. Map의 핵심 특징
 *    - Key(키) : 중복될 수 없습니다. (유일성 보장, 내부적으로 Set 구조)
 *    - Value(값) : 중복 저장이 가능합니다. (키가 다르면 값은 같아도 상관없음)
 *    - 순서를 보장하지 않습니다. (입력한 순서대로 출력되지 않을 수 있음)
 */
public class Map_09 {

	public static void main(String[] args) {
		// TODO Auto-generated method stub
		
		// -------------------------------------------------------------
		// 1. HashMap 객체 생성 (비제네릭 방식)
		// -------------------------------------------------------------
		// 키와 값 모두 Object 타입으로 처리되므로 어떤 자료형이든 자유롭게 담을 수 있습니다.
		HashMap map = new HashMap();
		
		// -------------------------------------------------------------
		// 2. 데이터 저장: put(키, 값)
		// -------------------------------------------------------------
		map.put("k1" , "v1");   // Key: "k1", Value: "v1" (문자열)
		map.put("k2" , 2);      // Key: "k2", Value: 2 (정수, 오토박싱)
		map.put("k3" , false);  // Key: "k3", Value: false (불리언)
		
		// [Map의 중요한 동작 원리: Key 중복 시 덮어쓰기]
		// 기존에 이미 "k2"라는 Key가 존재하므로, 새로운 데이터가 추가되는 것이 아니라
		// 기존 "k2"의 값(2)이 새로운 값(3)으로 '수정(Update, 덮어쓰기)'됩니다.
		map.put("k2" , 3);
		
		// -------------------------------------------------------------
		// 3. 데이터 조회: get(키)
		// -------------------------------------------------------------
		// Key를 전달하면 그에 연결된 Value를 반환합니다.
		System.out.println(map.get("k1")); // "v1" 출력
		
		// 비제네릭 맵에서 꺼낸 값은 'Object' 타입이므로, 원래 타입으로 쓰려면 형변환이 필요합니다.
		String s = (String)map.get("k1");
		
		// [없는 Key를 조회할 때의 동작]
		// 존재하지 않는 Key("k100")를 get()으로 조회하면 에러(예외)가 나는 것이 아니라 'null'을 돌려줍니다.
		System.out.println(map.get("k100")); // null 출력
		
		// -------------------------------------------------------------
		// 4. 제네릭 Map 선언 (실무 표준 방식)
		// -------------------------------------------------------------
		// Map<String, Integer>: "Key는 반드시 문자열(String), Value는 반드시 정수(Integer)만 넣겠다"는 의미입니다.
		// Map(인터페이스) 타입으로 선언하고 new HashMap()(구현 클래스)으로 생성합니다.
		Map<String, Integer> map2 = new HashMap();
		map2.put("k1", 1);
		
		// [주의/컴파일 에러 이유]
		// Value의 제네릭 타입을 Integer로 지정했기 때문에, 문자열 "1"을 넣으려고 하면 컴파일 에러가 발생합니다.
//		map2.put("k2", "1");
		
		// 제네릭 덕분에 꺼낼 때도 강제 형변환 없이 깔끔하게 Integer 변수로 바로 받을 수 있습니다.
		Integer a = map2.get("k2");
		
		// -------------------------------------------------------------
		// 5. 실무 응용 예제: 멜론 차트 (List 안에 Map 넣기)
		// -------------------------------------------------------------
		// - 멜론 차트 순위 목록(1위, 2위, 3위...) : 순서가 중요하므로 'List'로 관리
		// - 각 곡의 상세 정보(가수명, 제목...) : "제목":"With", "가수":"리센느" 처럼 항목별 매핑이 필요하므로 'Map'으로 관리
		// -> 즉, 엑셀 표의 각 '행(Row)'은 Map이 되고, 표 전체 '목록'은 List가 됩니다!
		List<Map<String, String>> melon = new ArrayList<Map<String, String>>();
		
		// 곡 정보(Map) 하나 생성
		Map<String, String> song = new HashMap<String, String>();
		song.put("제목", "With");
		song.put("가수" , "리센느");
		
		// 리스트에 곡 정보 맵을 추가 (1번 곡으로 등록)
		melon.add(song);
//		System.out.println("melon:" + melon);
		
		// 리스트를 순회하며 멜론 차트에 등록된 모든 곡의 정보를 출력
		for (int i=0; i< melon.size(); i++) {
			// 리스트에서 i번째 곡(Map)을 꺼내옴
			Map map3 = melon.get(i);
			System.out.println("map3: " + map3);
			// 꺼내온 Map에서 Key("제목", "가수")를 이용해 실제 값을 조회
			System.out.println("제목: " + map3.get("제목"));
			System.out.println("가수: " + map3.get("가수"));
		}
		
		// -------------------------------------------------------------
		// 6. final 키워드 (상수 만들기)
		// -------------------------------------------------------------
		// 일반 변수: 값을 언제든지 다른 값으로 변경(재대입)할 수 있습니다.
		int x = 10;
		x = 20; // 10 -> 20으로 값 변경 성공
		
		// final 변수: '최종적인 값'이라는 뜻으로, 한 번 초기화되면 값을 절대 바꿀 수 없는 '상수(Constant)'가 됩니다.
		final int y = 20;
		
		// [주의/컴파일 에러 이유]
		// y는 final로 선언되었으므로 값을 다시 대입하려고 하면 컴파일 에러("cannot assign a value to final variable")가 발생합니다.
//		y = 200;
		
		
	}

}