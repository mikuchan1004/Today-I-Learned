package var_02;

public class While_07 {

	public static void main(String[] args) {
		
		/* ====================================================================
		 * 1. while 반복문의 기본 구조
		 * ====================================================================
		 * - while(조건식) : 조건이 참(true)인 동안 계속해서 중괄호 내부를 반복 실행.
		 * - ★ 주의 : 반복문 안에 i++ 같은 '증감식'이 빠지면 i의 값이 변하지 않아
		 *   조건이 영원히 참이 되어 컴퓨터가 멈추지 않는 '무한 루프(Infinite Loop)'에 빠져!
		 */
		int i = 3;
		while(i < 10) {
			System.out.println(i);
			i++; // i를 1씩 증가 (3 -> 4 -> ... -> 10이 되면 탈출)
		}
		
		
		/* ====================================================================
		 * 2. do - while 반복문 (최소 1회 실행 보장)
		 * ====================================================================
		 * - 일반 while문은 시작하자마자 조건을 먼저 검사하지만,
		 *   do - while문은 조건을 '맨 마지막'에 검사해.
		 * - 따라서 조건이 처음부터 거짓(false)이더라도 본문을 '무조건 최소 1번'은 실행해!
		 *   (위에서 i가 이미 10이 된 상태지만, do 블록 안의 10이 1번 출력되고 i는 11이 됨)
		 */
		do {
			System.out.println(i);
			i++;
		}while(i < 10);
		
		System.out.println("----------------------");
		
		
		/* ====================================================================
		 * 3. continue 키워드를 활용한 짝수 출력
		 * ====================================================================
		 * - break    : 반복문을 그 즉시 완전히 중단하고 '탈출'
		 * - continue : 이번 턴의 남은 코드를 건너뛰고, 곧바로 '다음 반복 회차'로 넘어감!
		 * - 아래 코드 흐름:
		 *   i가 홀수(i % 2 != 0)이면 continue를 만나 밑의 println을 건너뛰고
		 *   다시 while 조건문으로 올라가므로 결과적으로 '짝수'만 화면에 출력돼.
		 */
		i = 0;
		while(i < 10) {
			i++;
			if(i % 2 != 0) { // 홀수 검증 조건
				continue;    // 홀수면 아래의 println을 건너뜀
			}
			System.out.println(i); // 짝수(2, 4, 6, 8, 10)만 출력됨
			
		}

	}

}
