package var_02;

import java.util.ArrayList;
import java.util.List;

/**
 * ============================================================================
 * [List_08.java - 컬렉션 프레임워크: ArrayList & List 다루기]
 * ============================================================================
 * 
 * 1. 컬렉션 프레임워크(Collection Framework)란?
 *    - 다수의 데이터를 쉽고 효율적으로 다룰 수 있도록 제공되는 자바의 표준 라이브러리입니다.
 *    - 일반 배열(Array)은 크기가 한 번 정해지면 바꿀 수 없지만, 
 *      ArrayList와 같은 컬렉션은 데이터가 추가/삭제됨에 따라 크기가 자동으로 늘어나고 줄어듭니다.
 * 
 * 2. List의 주요 특징
 *    - 순서(인덱스, 0부터 시작)가 유지됩니다.
 *    - 데이터의 중복 저장을 허용합니다.
 */
public class List_08 {

	public static void main(String[] args) {
		// TODO Auto-generated method stub

		// -------------------------------------------------------------
		// 1. ArrayList 객체 생성 (비제네릭 방식 - 옛날 방식)
		// -------------------------------------------------------------
		// 타입을 지정하지 않고 생성하면 내부적으로 모든 데이터를 최상위 클래스인 'Object'로 저장합니다.
		// 즉, 숫자, 문자열, 불리언 등 어떤 종류의 자료형이든 자유롭게 섞어서 담을 수 있습니다.
		ArrayList list = new ArrayList();

		// -------------------------------------------------------------
		// 2. 요소 추가: add(값)
		// -------------------------------------------------------------
		list.add(1);      // 정수 1 추가 (자바가 자동으로 기본형 int -> 참조형 Integer 객체로 감싸주는 '오토박싱' 수행)
		list.add("글씨");  // 문자열 "글씨" 추가 (String 객체)
		list.add(true);   // 불리언 true 추가 (기본형 boolean -> Boolean 객체로 오토박싱)

		// -------------------------------------------------------------
		// 3. 요소 꺼내기: get(인덱스 번호)
		// -------------------------------------------------------------
		// 인덱스는 배열과 마찬가지로 0번부터 시작합니다.
		System.out.println(list.get(0)); // 0번 위치의 값: 1
		System.out.println(list.get(1)); // 1번 위치의 값: "글씨"
		System.out.println(list.get(2)); // 2번 위치의 값: true

		// -------------------------------------------------------------
		// 4. 리스트의 크기(저장된 데이터 개수): size()
		// -------------------------------------------------------------
		// 일반 배열의 .length 와 동일한 역할을 메서드로 제공합니다.
		System.out.println(list.size()); // 현재 3개의 요소가 저장되어 있으므로 3 출력

		// -------------------------------------------------------------
		// 5. 반복문으로 list의 모든 내용을 출력하기
		// -------------------------------------------------------------
		
		// 방법 (1): 전통적인 for문 (인덱스 i를 이용)
		// 0번 인덱스부터 list.size() - 1 번 인덱스까지 하나씩 순회합니다.
		for (int i = 0; i < list.size(); i++) {
			System.out.println(list.get(i));
		}

		// 방법 (2): 향상된 for문 (for-each문)
		// list 안에 들어있는 요소를 처음부터 끝까지 하나씩 꺼내어 obj 변수에 담아 실행합니다.
		// 비제네릭 리스트이므로 꺼낸 요소는 가장 최상위 부모 타입인 'Object' 타입으로 받습니다.
		for (Object obj : list) {
			System.out.println(obj);
		}
		
		// -------------------------------------------------------------
		// 6. 비제네릭 방식의 단점: 형변환(Casting)의 번거로움
		// -------------------------------------------------------------
		// list.get(0)의 반환 타입은 'Object'입니다.
		// 따라서 기본형 int 변수에 바로 대입할 수 없고, 반드시 (int)로 강제 형변환(Casting)을 해주어야 합니다.
		int a = (int) list.get(0);
		String b = (String) list.get(1); // 1번 인덱스는 문자열이므로 (String) 형변환 필요
		
		// -------------------------------------------------------------
		// 7. 제네릭(Generic, <타입>)의 도입
		// -------------------------------------------------------------
		// 제네릭이란 리스트에 담을 데이터의 타입을 미리 지정해두는 문법입니다.
		// <String>을 지정하면 "이 리스트에는 오직 문자열(String)만 담겠다"는 약속입니다.
		ArrayList<String> list2 = new ArrayList<String>();
		list2.add("문자"); // String 타입이므로 정상 추가됨
		
		// [주의/에러 발생 이유]
		// 아래 코드를 실행하면 컴파일 오류가 납니다.
		// list2는 문자열 전용 리스트로 선언되었기 때문에, 정수(1)를 넣으려고 하면 자바 컴파일러가 입장을 차단합니다.
		// -> 컴파일 시점에 타입을 체크해주어 사전에 오류를 방지할 수 있습니다.
//		list2.add(1); 
		
		// [제네릭의 장점]
		// 요소를 꺼낼 때 번거롭게 (String) 형변환을 하지 않아도,
		// 자바가 이미 String 타입인 것을 알고 있으므로 곧바로 String 변수에 대입할 수 있습니다!
		String c = list2.get(0);
		
		// -------------------------------------------------------------
		// 8. 다형성을 활용한 인터페이스 선언 (실무 표준 권장 방식)
		// -------------------------------------------------------------
		// List는 상위 인터페이스이고, ArrayList는 이를 구현한 하위 클래스입니다.
		// 부모 인터페이스 타입(List)으로 참조 변수를 선언해두면,
		// 나중에 LinkedList 등 다른 List 구현체로 교체할 때도 코드를 유연하게 유지할 수 있습니다.
		List list3 = new ArrayList();
		
		// [주의/예외 발생 이유]
		// 현재 list2에는 0번 인덱스(1개)만 저장되어 있습니다.
		// 존재하지 않는 100번 인덱스를 조회하려고 하면 
		// 실행 도중 'IndexOutOfBoundsException'(인덱스 범위 초과) 예외가 발생하며 프로그램이 비정상 종료됩니다.
//		list2.get(100);

	}

}