package var_02;

public class Type_03 {

	public static void main(String[] args) {
		
		/* ====================================================================
		 * 1. StringBuffer (문자열을 자주 변경/추가할 때 사용하는 도구)
		 * ====================================================================
		 * - 일반 String은 한 번 만들어지면 수정할 수 없어서(불변, Immutable),
		 *   더하기(+) 연산을 할 때마다 새로운 문자열 객체를 메모리에 계속 생성해.
		 * - StringBuffer는 내부 메모리(버퍼) 공간을 늘려가며 문자열을 직접 이어붙이므로
		 *   문자열 결합 작업이 많을 때 메모리 낭비를 줄이고 속도를 훨씬 빠르게 해줘.
		 */
		StringBuffer sb = new StringBuffer();
		sb.append("A"); // 뒤에 "A"를 추가
		sb.append("B"); // 뒤에 "B"를 추가
		sb.append("C"); // 뒤에 "C"를 추가
		System.out.println("sb:" + sb); // 출력: ABC
		
		// StringBuffer를 일반 String 타입으로 변환하려면 toString() 메서드를 사용해.
		String s1 = sb.toString();
		
		
		/* ====================================================================
		 * 2. 배열(Array)의 선언과 참조 타입(Reference Type)의 특징
		 * ====================================================================
		 * - 배열은 "같은 자료형"의 여러 데이터를 한 줄로 나열해 보관하는 상자 묶음이야.
		 */
		int a1[];   // C 언어 스타일의 배열 선언 (자바에서도 지원하지만 비권장)
		int[] a2;   // 자바 공식 권장 스타일의 배열 선언 (타입 뒤에 []를 붙여 직관적임)
		// list[int] // 참고: 파이썬 스타일의 리스트 선언 방식
		int[][] a3; // 2차원 배열 (행과 열, 즉 표 형태의 배열)
		
		/*
		 * [null의 개념]
		 * - null이란 "참조하는 주소(대상이)가 없는 상태", 즉 허공을 가리키는 빈 상태를 의미해.
		 * - 기본 타입(Primitive type: int, double, boolean 등)에는 null을 넣을 수 없어.
		 *   예: int a = null; (컴파일 에러 발생!)
		 * - 참조 타입(Reference type: 배열, String, 클래스 객체 등)에만 null을 대입할 수 있어.
		 */
//		int a = null; // 에러: 기본형 변수는 실제 값(0, 1 등)만 저장 가능
		a1 = null;    // 정상: 배열 변수는 주소값을 저장하는 참조형이므로 null 가능
		
		
		/* ====================================================================
		 * 3. 배열 생성 및 요소 접근 (인덱스)
		 * ====================================================================
		 * - new int[30] : int형 방 30개를 힙(Heap) 메모리에 생성 (크기 30 고정)
		 * - 방 번호(인덱스)는 언제나 '0번'부터 시작해! (0 ~ 29번 방까지 존재)
		 * - 초기값을 안 넣으면 숫자형 배열은 자동으로 '0'으로 초기화돼.
		 */
		int[] a4 = new int[30];
		a4[0] = 10; // 첫 번째 방(0번 인덱스)에 10 저장
		a4[1] = 20; // 두 번째 방(1번 인덱스)에 20 저장
		
		System.out.println("a4[0]:" + a4[0]); // 특정 방의 값 확인 (10)
		System.out.println("a4:" + a4);       // 배열 변수 자체를 출력하면 메모리 주소(참조값)가 출력돼 (예: [I@15db9742)
//		a4[2] = null; // 에러: int형 배열의 각 칸은 기본형(int)이므로 null을 넣을 수 없어.
		
		
		/* ====================================================================
		 * 4. 배열 선언 및 초기화의 다양한 방법
		 * ====================================================================
		 */
		// 방법 1) new int[] {값1, 값2, ...} 로 선언과 동시에 값 채우기
		int[] a5 = new int[] {1,2,3,4};
		System.out.println("a5[2]:" + a5[2]); // 2번 인덱스(세 번째 값)인 3 출력
	
		// 방법 2) new 생략하고 중괄호만으로 간결하게 선언하기 (가장 많이 씀)
		int[] a6 = {1,2,3,4};
		System.out.println("a6.length:" + a6.length); // a6.length: 배열의 전체 방 개수(길이)인 4 출력
//		System.out.println(a6[100]); // 주의: 존재하지 않는 100번 인덱스 접근 시 ArrayIndexOutOfBoundsException 에러 발생!
		
		// for문으로 배열의 모든 요소 순회하며 출력하기
		int[] a = {1,2,3,4,5};
		for (int i=0; i<a.length; i++) {
			System.out.println(a[i]); // 0번부터 a.length - 1 번까지 차례대로 출력
		}
		
		
		/* ====================================================================
		 * 5. 2차원 배열 (행과 열, 아파트의 층과 호수)
		 * ====================================================================
		 * - int[][] 백자 = new int[3][10];
		 *   -> 3개 행(층), 각 행마다 10개 열(방)로 이루어진 총 30칸짜리 2차원 배열
		 */
		int[] floor1 = new int[10];
		int[] floor2 = new int[10];
		int[] floor3 = new int[10];

		int[][] 백자 = new int[3][10];
		System.out.println(백자);        // 2차원 배열의 주소값 출력 ([[I@...)
		System.out.println(백자.length); // 바깥 배열의 길이 = 행(층)의 개수 = 3
		
		// 1층(0번 인덱스 행)의 방 개수를 출력
		System.out.println(백자[0].length); // 10
		System.out.println(백자[0][0]);     // 기본값 출력 (int는 0, boolean은 false, 참조형은 null)
		
		// 각 행마다 열(방)의 개수가 서로 다른 '가변 배열'
		int[][] 백자2 = {
				{1,2,3},          // 0행: 방 3개
				{11,12,13},       // 1행: 방 3개
				{31,32,33,34}     // 2행: 방 4개
		};
		// 이중 for문을 이용해 2차원 배열의 모든 값 출력하기
		for (int i=0; i<백자2.length; i++) {         // i는 행(층) 인덱스
			for(int j=0; j<백자2[i].length; j++) { // j는 해당 행의 열(방) 인덱스
				System.out.println(백자2[i][j]);
			}
		}
		
		
		/* ====================================================================
		 * 6. 배열 실습 (1) : 배열 역순으로 뒤집기 (Reverse)
		 * ====================================================================
		 * - 원본 b = {7, 12, 8, 5} -> 뒤집은 결과 c = {5, 8, 12, 7}
		 * - 공식 유도:
		 *   c[0] = b[3] -> 인덱스 합이 항상 (length - 1)
		 *   따라서 c[i] = b[b.length - 1 - i]
		 */
		int [] b = {7,12,8,5};
		int [] c = new int[b.length];
		c[0] = b[3]; // length - (0+1) // length - 1 - 0
		c[1] = b[2]; // length - (1+2) // length - 1 - 1
		c[2] = b[1]; // length - (2+1)
		c[3] = b[0];
		
		// for문으로 자동화
		for (int i=0; i<b.length; i++) {
			c[i] = b[b.length -1 -i];
		}
		for (int i=0; i<c.length; i++) {
			System.out.println(c[i]);
		}
		
		
		/* ====================================================================
		 * 7. 배열 실습 (2) : 배열 맨 뒤에 새로운 값 추가하기
		 * ====================================================================
		 * - 자바의 기본 배열은 한 번 크기를 정하면 늘릴 수 없어(크기 고정).
		 * - 값을 추가하려면 길이가 '원본길이 + 1'인 새로운 큰 배열을 만들어
		 *   기존 데이터를 복사해 넣고 마지막 칸에 새 값을 넣어야 해.
		 */
		b = new int[] {7, 12, 8, 5};
		int new_value = 3;
		
		// 크기가 5(4 + 1)인 새로운 배열 생성
		int [] d = new int[b.length + 1];
		// 기존 b 배열의 값들을 그대로 복사
		for (int i=0; i<b.length; i++) {
			d[i] = b[i];
		}
		// 새로 늘어난 마지막 칸(인덱스 4)에 새 값 저장
		d[d.length - 1] = new_value;
		
		for (int i = 0; i < d.length; i++) {
            System.out.println("d[" + i + "] = " + d[i]);
        }
		
		
		/* ====================================================================
		 * 8. 배열 실습 (3) : 배열 맨 앞(0번 인덱스)에 3을 추가하기
		 * ====================================================================
		 * - 0번 자리에 새 값을 넣고, 기존 값들은 전부 한 칸씩 뒤로 밀어야 해 (i+1).
		 */
		int[] e = new int[b.length+1];
		e[0] = 3; // 맨 앞 칸에 3 삽입
		
		// 기존 값들을 1번 인덱스부터 차례대로 복사
		for (int i=0; i<b.length; i++) {
			e[i+1] = b[i];
		}
		
		
		/* ====================================================================
		 * 9. 배열 실습 (4) : 배열 내 조건 만족 개수 세기 (홀수의 개수)
		 * ====================================================================
		 * - % 2 == 1 은 홀수를 판별하는 공식이야.
		 */
		int count = 0;
		for (int i=0; i<e.length; i++) {
			if (e[i] % 2 == 1) {
				count++; // 홀수일 때마다 카운트 1 증가
			}
		}
		
		
		/* ====================================================================
		 * 10. 배열 실습 (5) : 배열의 특정 위치(인덱스 2번)에 값 삽입하기
		 * ====================================================================
		 * - [참고 노트]
		 *   원래 새 값을 삽입하면 총 길이가 1 늘어나야 하므로 new int[b.length + 1]이 정석이야.
		 *   (아래 코드는 크기가 b.length 그대로라서 마지막 요소가 잘리게 됨을 염두에 둘 것!)
		 * - 로직 흐름:
		 *   1) i < index  : 삽입 위치 전이므로 그대로 복사 f[i] = b[i]
		 *   2) i == index : 지정한 위치이므로 새 값 삽입 f[i] = value
		 *   3) i > index  : 삽입 위치 뒤이므로 앞 칸의 값을 당겨옴 f[i] = b[i-1]
		 */
		int index = 2;
		int value = 3;
		int [] f = new int[b.length];
		for (int i=0; i<f.length; i++) {
			if (i == index) {
				f[i] = value;
			
			}else if(i < index) {
				f[i] = b[i];
			}else if(i > index) {
				f[i] = b[i-1];
			}
		}
		for(int i=0; i<f.length; i++) {
			System.out.println(f[i]);
		}
   		
		/* ====================================================================
		 * 11. 주말 숙제 힌트 가이드
		 * ====================================================================
		 * [문제] 10자리 임시 비밀번호 만들기 (대문자 1개 이상, 소문자 1개 이상, 숫자 1개 이상 포함)
		 * [힌트]
		 * - 컴퓨터는 문자를 '아스키코드(숫자)'로 다뤄.
		 *   '0'~'9' : 48 ~ 57
		 *   'A'~'Z' : 65 ~ 90
		 *   'a'~'z' : 97 ~ 122
		 * - Math.random()으로 위 아스키코드 범위의 정수를 뽑은 뒤 (char)로 형변환하면
		 *   임의의 알파벳/숫자 문자를 얻을 수 있어.
		 */
		char lower = (char)((int)(Math.random() * ((122-97)+1))+97);
		System.out.println("lower:" + lower);
		
		String result = "";
		// 최종적으로 10번 반복하기
		// 대/소문자, 숫자를 랜덤으로 뽑아서 붙이기
		// 각각의 카운트를 기록해둘꺼임 
		// 8쯤에서 필수요소가 빠진게 있다면 채우기
		int cnt_upper = 0;
		int cnt_lower = 0;
		int cnt_num = 0;
		for (int i=0; i<10; i++) {
			int type = (int)(Math.random() * ((2-1)+1))+0;
			
			if (i >= 8) {
				if(cnt_upper < 1) {
					type = 0;
				}else if (cnt_lower < 1) {
					type = 1;
				}else if (cnt_num < 1) {
					type = 2;
				}
			}
			
			char val = 0;
			if (type == 0) {
				val = (char)((int)(Math.random() * ((90-65)+1))+65);
				cnt_upper++;
			}else if (type == 1) {
				val = (char)((int)(Math.random() * ((122-97)+1))+97);
				cnt_lower++;
			}else {
				val = (char)((int)(Math.random() * ((57-48)+1))+48);
				cnt_num++;
			}
			result += val;
		}
		System.out.println(result);
		
	}

}