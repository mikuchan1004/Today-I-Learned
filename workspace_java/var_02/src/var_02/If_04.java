package var_02;

public class If_04 {

	public static void main(String[] args) {
		
		/* ====================================================================
		 * 1. if - else if - else 기본 흐름
		 * ====================================================================
		 * - if (조건1)      : 조건1이 참이면 실행
		 * - else if (조건2) : 앞의 조건이 거짓이고 조건2가 참이면 실행
		 * - else            : 위의 모든 조건이 거짓일 때 실행
		 * - 위에서 아래로 순차 검사하며, 한 번이라도 조건을 만족하면 아래는 건너뜀!
		 */
		if(3 < 2) {
			System.out.println("3 < 2"); // 거짓이므로 통과
		}else if (3 != 3) {
			System.out.println("3 != 2"); // 거짓(3은 3과 같음)이므로 통과
		}else {
			System.out.println("else");   // 최종 실행됨
		}
		
		// 단순 if문 (조건이 참일 때만 실행)
		if(3 > 2) {
			System.out.println("3 > 2");
		}
		
		// 실행할 문장이 1줄일 때는 중괄호 {}를 생략할 수 있어.
		// (하지만 가독성과 실수를 방지하기 위해 평소엔 중괄호를 쓰는 게 좋아)
		if (3 > 2) System.out.println("3 > 2");
		else 	   System.out.println("거짓");
		
		
		/* ====================================================================
		 * 2. 기습문제 : 짝수 / 홀수 판별하기
		 * ====================================================================
		 * - % (나머지 연산자) : 어떤 수를 2로 나눈 나머지가 1이면 홀수, 0이면 짝수
		 */
		int a = 3;
		if (a % 2 == 1) {
			System.out.println("홀");
		} else {
			System.out.println("짝");
		}
	
		
		/* ====================================================================
		 * 3. Math.random()을 이용한 난수(랜덤 숫자) 생성 단계별 원리
		 * ====================================================================
		 * - Math.random()은 0.0 이상 1.0 미만(0.0 <= x < 1.0)의 double 실수를 반환해.
		 */
		double rand = Math.random();
		int min = 3;
		int max = 7;
		
		// 0.0 * 5 <= rand < 1.0 * 5  ==>  0.0 <= rand < 5.0
		rand = Math.random() * 5;
		System.out.println(rand);
		
		// [1단계] 0 ~ 7(max)까지의 정수 나오게 만들기
		// 1) 0.0 <= Math.random() < 1.0 에 (max + 1, 즉 8)을 곱하면: 0.0 <= x < 8.0
		// 2) (int)로 강제 형변환하여 소수점을 버리면: 0 ~ 7 정수가 됨
		rand = Math.random() * (max+1);
		rand = (int)(Math.random() * (max+1));
		
		// [2단계] 3(min) ~ 10까지 나오게 만들기
		// 0 ~ 7 범위의 정수에 최솟값 min(3)을 더하면 3 ~ 10이 됨
		rand = (int) (Math.random() * (max+1)) + min;
		
		// [3단계] 3(min) ~ 7(max)까지 나오게 만들기 (공식 유도)
		// * 핵심 공식 : (int)(Math.random() * (max - min + 1)) + min
		//   - 개수(경우의 수) = (max - min + 1) = 7 - 3 + 1 = 5개 (3, 4, 5, 6, 7)
		//   - (0~4까지 나온 정수) + 시작값(3) = 3 ~ 7
		// * 주의: 아래 코드의 ((min-max)+1)은 오타로 인해 음수가 나오므로 ((max-min)+1)이 올바른 공식이야!
		rand = (int) (Math.random() * ((min-max)+1)) + min;
		
		System.out.println(rand);
		
		// [번외 방법] 큰 난수를 생성한 뒤 나머지 연산자(%)로 범위 맞추기
		// 10000 이하의 큰 수를 경우의 수(5)로 나눈 나머지(0~4) + 시작값(3) -> 3 ~ 7
		rand = (int)(Math.random() * 10000) % ((max-min)+1) + min;
		
		
		/* ====================================================================
		 * 4. 0으로 나누기 오류와 단락 평가(Short-Circuit Evaluation)
		 * ====================================================================
		 */
		int num = 3;
		int num2 = 0;
		
		// [위험한 코드 예시]
		// 어떤 숫자든 0으로 나누면(/) 컴퓨터는 계산할 수 없어서 
		// 프로그램이 즉시 멈추고 런타임 에러(ArithmeticException: / by zero)를 발생시켜!
		if (num / num2 == 0) {
			System.out.println("참");
		}else {
			System.out.println("거짓");
		}
		
		// [안전한 코드 : 단락 평가(Short-circuit evaluation) 활용]
		// AND(&&) 연산자는 앞의 조건이 false이면, 뒤의 조건은 아예 쳐다보지도 않고 전체를 false로 결론내!
		// 따라서 num2 != 0 이 false(0이라는 뜻)이므로, 뒤쪽의 위험한 식(num / num2)을 아예 실행하지 않아
		// 0으로 나누는 에러를 안전하게 방지할 수 있어.
		if (num2 != 0 && num / num2 == 0) {
			System.out.println("참");
		}else {
			System.out.println("거짓");
		}
		
	}

}
